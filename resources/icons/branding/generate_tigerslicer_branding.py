#!/usr/bin/env python3
"""Deterministic TigerSlicer branding asset generator.

The TigerSlicer mark is two pink half-discs (the "S" of a sliced cylinder)
on a black disc:

    canvas    800 x 800, background disc  centre (400,400) r 400  #000000
    upper arc half-disc  centre (429.3,356.8) r 240.4, upper-left half
    lower arc half-disc  centre (372.7,442.5) r 240.4, lower-right half
    pink      #F4A7C6 (244,167,198)  -- both arcs, same shade

This script writes the canonical SVGs *and* rasterises the same geometry
with Pillow (no SVG renderer needed), so every PNG/ICO/ICNS shipped by the
app is derived from one definition. Do not hand-edit the outputs.

Requirements (developer tooling, not needed at build time):
    pip install pillow

Run from anywhere:  python resources/icons/branding/generate_tigerslicer_branding.py
"""

import math
import os
import sys

from PIL import Image, ImageDraw, ImageFilter, ImageFont, ImageOps

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import tigerslicer_wordmark as wm  # noqa: E402  (traced "tiger" / "slicer" outlines)

RES = os.path.abspath(os.path.join(HERE, "..", ".."))       # resources/
IMAGES = os.path.join(RES, "images")
WEB_IMAGE = os.path.join(RES, "web", "image")

PINK = (244, 167, 198, 255)
BLACK = (0, 0, 0, 255)
PINK_HEX = "#f4a7c6"
GRAY_HEX = "#949494"     # "slicer" in the wordmark, as in the original

CANVAS = 800.0
ARC_R = 240.4
UPPER = (429.3, 356.8)   # centre of upper-left half-disc
LOWER = (372.7, 442.5)   # centre of lower-right half-disc
SUPERSAMPLE = 4
MASTER_PX = 1024

ICO_SIZES = [16, 24, 32, 48, 64, 128, 256]
ICNS_SIZES = [16, 32, 64, 128, 256, 512, 1024]

# ---------------------------------------------------------------- SVG ----

MARK_PATHS = (
    '<path d="M599.3,186.8c-93.9-93.9-246.1-93.9-340,0s-93.9,246.1,0,340Z" fill="{pink}"/>\n'
    '<path d="M202.7,612.5c93.9,93.9,246.1,93.9,340,0s93.9-246.1,0-340" fill="{pink}"/>'
)


def mark_svg(pink=PINK_HEX, bg="#000", comment=True):
    head = ""
    if comment:
        head = ("<!-- TigerSlicer brand mark: two pink half-discs on a black disc.\n"
                "     Generated by resources/icons/branding/generate_tigerslicer_branding.py;\n"
                "     edit the constants there, not this file. -->\n")
    return ('<svg xmlns="http://www.w3.org/2000/svg" width="800" height="800" viewBox="0 0 800 800">\n'
            + head +
            f'<circle cx="400" cy="400" r="400" fill="{bg}"/>\n'
            + MARK_PATHS.format(pink=pink) + "\n</svg>\n")


def mark_group(x, y, size, pink=PINK_HEX, bg="#000"):
    """The mark as an inline <g>, fitted into a size x size box at (x, y)."""
    s = size / CANVAS
    return (f'<g transform="translate({x:g} {y:g}) scale({s:.6f})">'
            f'<circle cx="400" cy="400" r="400" fill="{bg}"/>'
            + MARK_PATHS.format(pink=pink).replace("\n", "") + "</g>")


def write(path, text):
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    print(f"  {os.path.relpath(path, RES)}")


def wordmark_group(x, baseline, xheight, path, fill):
    """One traced word, scaled so its x-height is `xheight`, baseline at y."""
    s = xheight / wm.XHEIGHT
    return (f'<g transform="translate({x:g} {baseline:g}) scale({s:.6f})">'
            f'<path d="{path}" fill="{fill}"/></g>')


def header_svg(width, height, box, text_x, tiger, slicer, underline=None):
    """Logo + "tiger / slicer" wordmark, as used by the About dialog and the
    Troubleshoot header. `tiger`/`slicer` are (baseline, xheight) pairs."""
    body = ""
    if underline:
        body += f'<rect x="{underline[0]}" y="{underline[1]}" width="{underline[2]}" height="2" fill="{PINK_HEX}"/>'
    body += mark_group(*box)
    body += wordmark_group(text_x, tiger[0], tiger[1], wm.TIGER_PATH, PINK_HEX)
    body += wordmark_group(text_x, slicer[0], slicer[1], wm.SLICER_PATH, GRAY_HEX)
    return ('<?xml version="1.0" encoding="UTF-8"?>'
            f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" '
            f'viewBox="0 0 {width} {height}">{body}</svg>\n')


def write_header_svgs():
    # About dialog (560x125): mark in an 80.56 box, wordmark to its right,
    # pink rule along the bottom. Geometry follows the original layout.
    about = header_svg(560, 125, (20, 21.22, 80.56), 115.6,
                       tiger=(60.9, 30), slicer=(91.9, 18.5),
                       underline=(20, 123, 520))
    # Troubleshoot header (214x80): tighter, the wordmark fits the width.
    horiz = header_svg(214, 80, (0, 0, 80), 95,
                       tiger=(39.4, 28), slicer=(70.2, 18.5))
    for name in ("OrcaSlicer_about.svg", "OrcaSlicer_about_dark.svg"):
        write(os.path.join(IMAGES, name), about)
    for name in ("OrcaSlicer_horizontal_light.svg", "OrcaSlicer_horizontal_dark.svg"):
        write(os.path.join(IMAGES, name), horiz)

# ------------------------------------------------------------ splash ----

# Startup card (resources/images/splash_tigerslicer.svg). SplashScreen in
# GUI_App.cpp draws the version, status line and progress bar over it, and its
# card size must stay SPLASH_W x SPLASH_H. Always dark, whatever the UI theme.
# Avoid #949494 / "#F6A5C1" / "#D98BA8" here: BitmapCache::load_svg recolours them.
SPLASH_W, SPLASH_H = 560, 340
SPLASH_BG = "#0e0e10"
SPLASH_SLICER = "#c9c9ce"    # "slicer", light enough to read on black
SPLASH_MARK = 120            # mark diameter
SPLASH_CY = 124              # centre line of the lockup (the mark's centre)
SPLASH_GLOW = 210            # radius of the pink halo behind the mark


def mix(a, b, f):
    """The colour a + (b - a) * f, for "#rrggbb" strings."""
    ca, cb = ([int(c[i:i + 2], 16) for i in (1, 3, 5)] for c in (a, b))
    return "#" + "".join(f"{round(x + (y - x) * f):02x}" for x, y in zip(ca, cb))


def lockup_group(x, y, size, slicer_fill):
    """Mark with "tiger / slicer" beside it, in the About-dialog proportions
    (mark 80.56, text at +95.6, baselines at +39.68 / +70.68, x-heights 30 /
    18.5), scaled so the mark is `size` and its top-left corner is (x, y)."""
    s = size / 80.56
    tx = x + 95.6 * s
    return (mark_group(x, y, size)
            + wordmark_group(tx, y + 39.68 * s, 30 * s, wm.TIGER_PATH, PINK_HEX)
            + wordmark_group(tx, y + 70.68 * s, 18.5 * s, wm.SLICER_PATH, slicer_fill))


def splash_svg():
    """Near-black card, a faint pink halo around the black disc, and the
    lockup centred horizontally. nanosvg-safe: no text, CSS, filters or masks."""
    s = SPLASH_MARK / 80.56
    width = (95.6 + 30 * wm.TIGER_ADVANCE / wm.XHEIGHT) * s   # mark + gap + "tiger"
    x = round((SPLASH_W - width) / 2, 2)
    cx = x + SPLASH_MARK / 2
    centre = f'cx="{cx:g}" cy="{SPLASH_CY}" fx="{cx:g}" fy="{SPLASH_CY}" r="{SPLASH_GLOW}"'
    # 30% pink fading out quadratically (flat at the rim, so the halo has no
    # edge). Stops are pre-blended onto the background: an opaque gradient
    # avoids nanosvg's alpha rounding, which leaves a ring darker than the card.
    stops = "".join(f'<stop offset="{t:g}" stop-color="{mix(SPLASH_BG, PINK_HEX, 0.3 * (1 - t) ** 2)}"/>'
                    for t in (0, 0.25, 0.5, 0.75, 1))
    glow = f'<radialGradient id="glow" gradientUnits="userSpaceOnUse" {centre}>{stops}</radialGradient>'
    card = f'width="{SPLASH_W}" height="{SPLASH_H}"'
    return ('<?xml version="1.0" encoding="UTF-8"?>\n'
            f'<svg xmlns="http://www.w3.org/2000/svg" {card} viewBox="0 0 {SPLASH_W} {SPLASH_H}">\n'
            "<!-- TigerSlicer startup card. Generated by\n"
            "     resources/icons/branding/generate_tigerslicer_branding.py; do not edit. -->\n"
            f"<defs>{glow}</defs>\n"
            f'<rect {card} fill="{SPLASH_BG}"/>\n'
            f'<rect {card} fill="url(#glow)"/>\n'
            + lockup_group(x, SPLASH_CY - SPLASH_MARK / 2, SPLASH_MARK, SPLASH_SLICER)
            + "\n</svg>\n")

# -------------------------------------------------------- bed texture ----

# Bed texture of the Custom printers (resources/profiles/Custom). PartPlate
# stretches the 512 x 512 canvas over the bed: corner marks at the bed corners
# and the lockup centred along the front edge, where the original logo was.
BED_SIZE = 512
BED_MARK_BOX = (185.9, 441.26, 52.46)   # x, y, size of the mark
BED_SLICER = "#9b9ba1"                  # "slicer", readable on light and dark beds (not #949494, see above)
BED_CORNERS = (
    "M511.15,502.65c0,4.7-3.81,8.5-8.5,8.5h-10.07v.85h19.42v-19.42h-.85v10.07Z",
    "M9.35,511.15c-4.7,0-8.5-3.81-8.5-8.5v-10.07h-.85v19.42h19.42v-.85h-10.07Z",
    "M.85,9.35C.85,4.65,4.65.85,9.35.85h10.07V0H0v19.42h.85v-10.07Z",
    "M502.65.85c4.7,0,8.5,3.81,8.5,8.5v10.07h.85V0h-19.42v.85h10.07Z",
)


def bed_texture_svg():
    """Transparent canvas, pink corner marks, mark + "tiger / slicer"."""
    corners = "".join(f'<path d="{d}" fill="{PINK_HEX}"/>' for d in BED_CORNERS)
    size = f'width="{BED_SIZE}" height="{BED_SIZE}"'
    return ('<?xml version="1.0" encoding="UTF-8"?>\n'
            f'<svg xmlns="http://www.w3.org/2000/svg" {size} viewBox="0 0 {BED_SIZE} {BED_SIZE}">\n'
            "<!-- TigerSlicer bed texture. Generated by\n"
            "     resources/icons/branding/generate_tigerslicer_branding.py; do not edit. -->\n"
            + corners + lockup_group(*BED_MARK_BOX, BED_SLICER)
            + "\n</svg>\n")


def write_bed_texture():
    write(os.path.join(RES, "profiles", "Custom", "tigerslicer_bed_texture.svg"), bed_texture_svg())


# Printer-list pictures of the generic resin printers. Like the generic FDM printers' firmware
# logos (resources/profiles/Custom/*_cover.png): a rounded tile with a symbol and a name. The
# symbol is an MSLA printer: Z rail, build plate with a print hanging from it, resin vat, LCD.
GENERIC_RESIN_TILES = {
    "Generic 2K MSLA 1620x2560 (82.6 x 130.6 mm)": "2K",
    "Generic 3840x2400 MSLA": "4K",
    "Generic 6K MSLA 5760x3600 (198.1 x 123.8 mm)": "6K",
    "Generic 8K MSLA 7680x4320 (218.9 x 123.1 mm)": "8K",
    "Generic 10K MSLA 10240x5120 (228.4 x 114.2 mm)": "10K",
}
TILE_PX = 240
TILE_RADIUS = 24
TILE_INK = (14, 14, 16, 255)
TILE_RESIN = (196, 112, 150, 255)
TILE_FONT = os.path.join(RES, "fonts", "HarmonyOS_Sans_SC_Bold.ttf")


def generic_resin_tile(label):
    """240x240 tile in TIGER pink: the MSLA symbol over "<label> MSLA", in 240-px units."""
    k = SUPERSAMPLE
    img = Image.new("RGBA", (TILE_PX * k, TILE_PX * k), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)

    def box(x0, y0, x1, y1, fill, r=0):
        d.rounded_rectangle([x0 * k, y0 * k, x1 * k - 1, y1 * k - 1], radius=r * k, fill=fill)

    box(0, 0, TILE_PX, TILE_PX, PINK, TILE_RADIUS)
    box(176, 20, 190, 156, TILE_INK, 3)                 # Z rail, beside the vat
    box(110, 46, 182, 58, TILE_INK, 3)                  # arm from the rail to the plate
    box(110, 46, 122, 70, TILE_INK)                     # plate stem
    box(46, 100, 166, 148, TILE_INK, 6)                 # vat
    box(54, 100, 158, 140, PINK)                        # vat inside, open at the top
    box(54, 118, 158, 140, TILE_RESIN)                  # resin
    box(58, 68, 154, 80, TILE_INK, 4)                   # build plate
    box(80, 78, 132, 128, TILE_INK, 8)                  # print, hanging from the plate into the resin
    box(36, 152, 204, 164, TILE_INK, 3)                 # LCD

    text = f"{label} MSLA"
    size = 44
    font = ImageFont.truetype(TILE_FONT, size * k)
    while d.textlength(text, font=font) > 200 * k:
        size -= 2
        font = ImageFont.truetype(TILE_FONT, size * k)
    d.text((TILE_PX * k / 2, 198 * k), text, font=font, fill=TILE_INK, anchor="mm")
    return img.resize((TILE_PX, TILE_PX), Image.LANCZOS)


def write_generic_resin_tiles():
    print("resources/profiles/TigerSlicerResin ->")
    for model, label in GENERIC_RESIN_TILES.items():
        save_png(generic_resin_tile(label),
                 os.path.join(RES, "profiles", "TigerSlicerResin", f"{model}_thumbnail.png"))

# ------------------------------------------------------------- raster ----


def render_master(size=MASTER_PX, pink=PINK, bg=BLACK):
    """Rasterise the mark to an RGBA square (transparent outside the disc)."""
    W = int(CANVAS * SUPERSAMPLE)
    img = Image.new("RGBA", (W, W), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    k = SUPERSAMPLE
    d.ellipse([0, 0, W - 1, W - 1], fill=bg)
    r = ARC_R * k
    cx, cy = UPPER[0] * k, UPPER[1] * k
    d.pieslice([cx - r, cy - r, cx + r, cy + r], 135, 315, fill=pink)   # upper-left half
    cx, cy = LOWER[0] * k, LOWER[1] * k
    d.pieslice([cx - r, cy - r, cx + r, cy + r], 315, 135, fill=pink)   # lower-right half
    return img.resize((size, size), Image.LANCZOS)


def sized(master, px):
    return master.resize((px, px), Image.LANCZOS)


def save_png(image, path):
    image.save(path, format="PNG", optimize=True)
    print(f"  {os.path.relpath(path, RES)}  {image.size[0]}x{image.size[1]}")


def save_ico(master, path, sizes=ICO_SIZES):
    frames = [sized(master, px) for px in sorted(sizes, reverse=True)]
    frames[0].save(path, format="ICO", sizes=[(px, px) for px in sizes],
                   append_images=frames[1:])
    print(f"  {os.path.relpath(path, RES)}  sizes {sizes}")


def save_icns(master, path):
    frames = [sized(master, px) for px in ICNS_SIZES]
    frames[-1].save(path, format="ICNS", append_images=frames[:-1])
    print(f"  {os.path.relpath(path, RES)}  sizes {ICNS_SIZES}")


def grayscale(image):
    g = ImageOps.grayscale(image).convert("RGBA")
    g.putalpha(image.getchannel("A"))
    return g


def padded(master, width, height):
    """Mark centred on a transparent width x height canvas."""
    px = min(width, height)
    out = Image.new("RGBA", (width, height), (0, 0, 0, 0))
    out.paste(sized(master, px), ((width - px) // 2, (height - px) // 2))
    return out


def document_icon(master):
    """macOS document-type icon: white rounded page carrying the mark."""
    W = MASTER_PX
    page = Image.new("RGBA", (W, W), (0, 0, 0, 0))
    d = ImageDraw.Draw(page)
    d.rounded_rectangle([W * 0.16, W * 0.06, W * 0.84, W * 0.94], radius=W * 0.06,
                        fill=(236, 236, 236, 255), outline=(200, 200, 200, 255), width=6)
    badge = sized(master, int(W * 0.5))
    page.paste(badge, ((W - badge.width) // 2, (W - badge.height) // 2), badge)
    return page


# macOS app icon grid (Big Sur and later): an 824 px body centred on a
# 1024 px canvas, continuous-corner "squircle" outline, soft drop shadow.
MAC_BODY = 824
MAC_SQUIRCLE_N = 5.0          # superellipse exponent approximating Apple's corners
MAC_TOP = (34, 34, 36, 255)   # body gradient, top -> bottom
MAC_BOTTOM = (0, 0, 0, 255)
MAC_MARK = 0.88               # mark disc diameter relative to the body
MAC_SHADOW = (12, 14, 0.35)   # y offset, blur radius (px at 1024), opacity


def squircle_mask(size, body, k):
    """Superellipse of `body` px centred on a `size` px canvas, at k-x supersampling."""
    W, a, c = size * k, body * k / 2, size * k / 2
    e = 2 / MAC_SQUIRCLE_N
    pts = []
    for i in range(4096):
        t = 2 * math.pi * i / 4096
        ct, st = math.cos(t), math.sin(t)
        pts.append((c + a * math.copysign(abs(ct) ** e, ct),
                    c + a * math.copysign(abs(st) ** e, st)))
    mask = Image.new("L", (W, W), 0)
    ImageDraw.Draw(mask).polygon(pts, fill=255)
    return mask


def macos_app_icon(size=MASTER_PX):
    """The mark on a macOS-style rounded square, so the Dock and Finder show
    it at the same size and shape as other Mac apps. Used only by the Mac
    bundle icon (Icon.icns) and the Dock icon (*-mac_* files)."""
    k = SUPERSAMPLE
    W = size * k
    scale = size / 1024 * k
    body = squircle_mask(size, MAC_BODY * size / 1024, k)
    _, y0, _, y1 = body.getbbox()

    # Body: a top-to-bottom gradient clipped to the squircle.
    ramp = Image.new("RGBA", (1, 2))
    ramp.putpixel((0, 0), MAC_TOP)
    ramp.putpixel((0, 1), MAC_BOTTOM)
    face = Image.new("RGBA", (W, W), (0, 0, 0, 0))
    face.paste(ramp.resize((W, y1 - y0), Image.BILINEAR), (0, y0))
    face.putalpha(body)

    # Drop shadow: the body shape, offset down and blurred.
    dy, blur, opacity = MAC_SHADOW
    shadow = Image.new("L", (W, W), 0)
    shadow.paste(body.point(lambda p: round(p * opacity)), (0, round(dy * scale)))
    icon = Image.new("RGBA", (W, W), (0, 0, 0, 0))
    icon.putalpha(shadow.filter(ImageFilter.GaussianBlur(blur * scale)))
    icon = Image.alpha_composite(icon, face)

    # The mark's pink half-discs (its black disc disappears into the body).
    d = ImageDraw.Draw(icon)
    disc = MAC_BODY * MAC_MARK * scale
    s, off = disc / CANVAS, (W - disc) / 2
    r = ARC_R * s
    cx, cy = off + UPPER[0] * s, off + UPPER[1] * s
    d.pieslice([cx - r, cy - r, cx + r, cy + r], 135, 315, fill=PINK)
    cx, cy = off + LOWER[0] * s, off + LOWER[1] * s
    d.pieslice([cx - r, cy - r, cx + r, cy + r], 315, 135, fill=PINK)
    return icon.resize((size, size), Image.LANCZOS)

# --------------------------------------------------------------- main ----


def generate_branding_dir(master, mac):
    print("resources/icons/branding ->")
    for base in ("TigerSlicer", "TigerSlicer-gcodeviewer"):
        write(os.path.join(HERE, f"{base}.svg"), mark_svg())
        if base == "TigerSlicer":
            save_png(sized(master, 154), os.path.join(HERE, f"{base}.png"))
            save_png(grayscale(sized(master, 192)), os.path.join(HERE, f"{base}_192px_grayscale.png"))
            save_png(sized(master, 192), os.path.join(HERE, f"{base}_192px_transparent.png"))
        save_png(sized(master, 192), os.path.join(HERE, f"{base}_192px.png"))
        save_png(sized(master, 128), os.path.join(HERE, f"{base}_128px.png"))
        save_png(sized(master, 32), os.path.join(HERE, f"{base}_32px.png"))
        save_png(sized(mac, 128), os.path.join(HERE, f"{base}-mac_128px.png"))
        save_ico(master, os.path.join(HERE, f"{base}.ico"))
        save_icns(mac, os.path.join(HERE, f"{base}.icns"))


def generate_app_images(master, mac):
    """The files the application, installer and bundles actually load."""
    print("resources/images ->")

    def img(name):
        return os.path.join(IMAGES, name)

    # Square logo SVGs (splash, home page badge, legacy gradient names).
    for name in ("OrcaSlicer.svg", "splash_logo.svg", "splash_logo_dark.svg",
                 "OrcaSlicer_gradient.svg", "OrcaSlicer_gradient_circle.svg",
                 "OrcaSlicer_gradient_narrow.svg", "TigerSlicer_gradient.svg",
                 "TigerSlicer_gradient_circle.svg", "TigerSlicer_gradient_narrow.svg"):
        write(img(name), mark_svg())
    write(img("OrcaSlicer_gray.svg"), mark_svg(pink="#bdbdbd", bg="#000"))

    # Logo + wordmark SVGs: About dialog and Troubleshoot header.
    write_header_svgs()

    # Startup splash card.
    write(img("splash_tigerslicer.svg"), splash_svg())

    # Custom printers' bed texture.
    write_bed_texture()

    # Rasters referenced from C++ / CMake / plists.
    save_png(sized(master, 154), img("OrcaSlicer.png"))
    save_png(sized(master, 154), img("OrcaSlicerTitle.png"))
    save_png(sized(master, 154), img("OrcaSlicer_154.png"))
    save_png(padded(master, 184, 184), img("OrcaSlicer_154_title.png"))
    save_png(sized(master, 128), img("OrcaSlicer_128px.png"))
    save_png(sized(mac, 128), img("OrcaSlicer-mac_128px.png"))
    save_png(sized(master, 192), img("OrcaSlicer_192px.png"))
    save_png(sized(master, 192), img("OrcaSlicer_192px_transparent.png"))
    save_png(grayscale(sized(master, 192)), img("OrcaSlicer_192px_grayscale.png"))
    save_png(sized(master, 64), img("OrcaSlicer_64.png"))
    save_png(sized(master, 32), img("OrcaSlicer_32px.png"))
    save_ico(master, img("OrcaSlicer.ico"))
    save_ico(master, img("OrcaSlicerTitle.ico"))
    # Mac app icon: bundle icon (Icon.icns) and the Dock icon MainFrame sets
    # at runtime (OrcaSlicer-mac_256px.ico). OrcaSlicer.icns is the plist's
    # document-type icon and keeps the round mark.
    save_ico(mac, img("OrcaSlicer-mac_256px.ico"), sizes=[16, 32, 48, 64, 128, 256])
    save_icns(master, img("OrcaSlicer.icns"))
    save_icns(mac, os.path.join(RES, "Icon.icns"))

    # macOS document-type icons for .stl / .gcode associations.
    doc = document_icon(master)
    save_icns(doc, img("stl.icns"))
    save_icns(doc, img("gcode.icns"))

    # Web home page / guide pages.
    print("resources/web/image ->")
    save_png(sized(master, 154), os.path.join(WEB_IMAGE, "logo.png"))
    save_png(padded(master, 339, 406), os.path.join(WEB_IMAGE, "logo2.png"))


def main():
    master = render_master()
