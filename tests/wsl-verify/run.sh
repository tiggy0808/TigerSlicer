#!/usr/bin/env bash
# TigerSlicer pure-logic verification harness for WSL/Linux.
#
# Windows Smart App Control (enforced) rejects newly linked test executables on
# this machine, so the Catch2 suites cannot be started after a relink. Linux
# binaries built inside WSL are not subject to that policy, which lets the
# dependency-light, platform-independent logic keep real execution coverage.
#
# This harness deliberately compiles the SAME production translation units the
# Windows build uses - it never re-implements the logic under test. The Catch2
# suites remain authoritative; this is a second execution path, not a
# replacement.
#
# Usage (from the repository root):
#   wsl -d Ubuntu -- bash tests/wsl-verify/run.sh
set -uo pipefail

REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
DEPS_ROOT="/mnt/c/src/TigerSlicer-deps/usr/local/include"
DEPS_INCLUDE="${DEPS_ROOT}/boost-1_83"
OUT="${REPO}/build/wsl-verify"
mkdir -p "${OUT}"

if [[ ! -d "${DEPS_INCLUDE}" ]]; then
    echo "SKIP: boost headers not found at ${DEPS_INCLUDE}" >&2
    exit 2
fi

# libslic3r_version.h is generated by the CMake configure step; reuse the one
# the Windows build already produced rather than duplicating its contents.
GENERATED_INCLUDE="${REPO}/build/src/libslic3r"
if [[ ! -f "${GENERATED_INCLUDE}/libslic3r_version.h" ]]; then
    echo "SKIP: generated libslic3r_version.h not found; configure the build first" >&2
    exit 2
fi

CXXFLAGS=(-std=c++17 -O1 -Wall -Wextra -Wno-unused-parameter
          -I"${REPO}/src" -I"${DEPS_INCLUDE}" -I"${DEPS_ROOT}"
          -I"${GENERATED_INCLUDE}" -I"${REPO}/bundled_deps/semver"
          -I"${DEPS_ROOT}/eigen3" -I"${REPO}/bundled_deps/localesutils")

fail=0
run_case() {
    local name="$1"; shift
    echo "== ${name}"
    if g++ "${CXXFLAGS[@]}" -o "${OUT}/${name}" "$@" 2> "${OUT}/${name}.build.log"; then
        if "${OUT}/${name}"; then
            echo "   PASS"
        else
            echo "   FAIL (runtime)"; fail=1
        fi
    else
        echo "   FAIL (build) - see ${OUT}/${name}.build.log"
        tail -20 "${OUT}/${name}.build.log" >&2
        fail=1
    fi
}

run_case discovery_model \
    "${REPO}/tests/wsl-verify/discovery_model_main.cpp" \
    "${REPO}/src/slic3r/Utils/PrinterDiscoveryModel.cpp"

if [[ ${fail} -ne 0 ]]; then
    echo "WSL verification FAILED"
    exit 1
fi
echo "WSL verification passed"
