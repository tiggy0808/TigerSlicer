#!/usr/bin/env bash
# Build the TigerSlicer dependencies that Ubuntu does not package, at the exact
# revisions pinned in deps/, into a user-local prefix. No sudo, no system
# changes; delete ${DEPS_PREFIX} to undo.
#
# Usage: wsl -d Ubuntu -- bash tests/wsl-verify/linux-deps.sh
set -euo pipefail

DEPS_PREFIX="${TS_LINUX_DEPS_PREFIX:-$HOME/tsdeps/prefix}"
SRC="${TS_LINUX_DEPS_SRC:-$HOME/tsdeps/src}"
export CMAKE_POLICY_VERSION_MINIMUM=3.5
mkdir -p "${SRC}" "${DEPS_PREFIX}"

# fetch <name> <url> <sha256>
fetch() {
    local name="$1" url="$2" sha="$3"
    if [[ -d "${SRC}/${name}" ]]; then return 0; fi
    echo "-- fetching ${name}"
    curl -sL -o "${SRC}/${name}.zip" "${url}"
    echo "${sha}  ${SRC}/${name}.zip" | sha256sum -c - > /dev/null
    # The archive's top-level directory name varies in case and suffix, so
    # discover it rather than assuming it matches ${name}.
    ( cd "${SRC}" && rm -rf .unpack && mkdir .unpack && cd .unpack &&
      unzip -q -o "../${name}.zip" &&
      mv "$(ls -1 | head -1)" "../${name}" && cd .. && rm -rf .unpack )
}

# LibBGCode - pinned in deps/+LibBGCode/LibBGCode.cmake
fetch libbgcode \
    "https://github.com/prusa3d/libbgcode/archive/6f4ad7ce6b0e638b760199d6611039a610a5a479.zip" \
    "1e91c944a52022e8af46b05b463add59b3ac011a5e1982e60891d41149c56144"
if [[ ! -f "${DEPS_PREFIX}/lib/cmake/LibBGCode/LibBGCodeConfig.cmake" ]]; then
    echo "-- building LibBGCode"
    cmake -S "${SRC}/libbgcode" -B "${SRC}/libbgcode/b" -G Ninja \
        -DCMAKE_BUILD_TYPE=Release -DCMAKE_INSTALL_PREFIX="${DEPS_PREFIX}" \
        -DLibBGCode_BUILD_TESTS=OFF -DLibBGCode_BUILD_CMD_TOOL=OFF > /dev/null
    cmake --build "${SRC}/libbgcode/b" --target install > /dev/null
fi

# NanoSVG - pinned in deps/+NanoSVG/NanoSVG.cmake
fetch nanosvg \
    "https://github.com/fltk/nanosvg/archive/abcd277ea45e9098bed752cf9c6875b533c0892f.zip" \
    "e859938fbaee4b351bd8a8b3d3c7a75b40c36885ce00b73faa1ce0b98aa0ad34"
if [[ ! -f "${DEPS_PREFIX}/lib/cmake/NanoSVG/nanosvgConfig.cmake" && \
      ! -f "${DEPS_PREFIX}/lib/cmake/nanosvg/nanosvgConfig.cmake" ]]; then
    echo "-- building NanoSVG"
    cmake -S "${SRC}/nanosvg" -B "${SRC}/nanosvg/b" -G Ninja \
        -DCMAKE_BUILD_TYPE=Release -DCMAKE_INSTALL_PREFIX="${DEPS_PREFIX}" > /dev/null
    cmake --build "${SRC}/nanosvg/b" --target install > /dev/null
fi

# CGAL - pinned in deps/+CGAL/CGAL.cmake. The distribution ships CGAL 6, whose
# property_map() and AABB_traits APIs are incompatible with the sources; CGAL
# is header-only, so install the pinned 5.x headers instead of porting code.
fetch cgal \
    "https://github.com/CGAL/cgal/archive/refs/tags/v5.6.2.zip" \
    "29acaeee5a76a95029fac23131bb1c3a4a75df9a0e7e43b465a1f32d0628f45d"
if [[ ! -f "${DEPS_PREFIX}/lib/cmake/CGAL/CGALConfig.cmake" ]]; then
    echo "-- installing CGAL 5.6.2 headers"
    cmake -S "${SRC}/cgal" -B "${SRC}/cgal/b" -G Ninja \
        -DCMAKE_BUILD_TYPE=Release -DCMAKE_INSTALL_PREFIX="${DEPS_PREFIX}" \
        -DCGAL_HEADER_ONLY=ON > /dev/null
    cmake --build "${SRC}/cgal/b" --target install > /dev/null
fi

# Catch2 - pinned in deps/+Catch2/Catch2.cmake; the distribution package is
# older than the version the test targets require.
fetch catch2 \
    "https://github.com/catchorg/Catch2/archive/refs/tags/v3.8.0.zip" \
    "bffd2c45a84e5a4b0c17e695798e8d2f65931cbaf5c7556d40388d1d8d04eb83"
if [[ ! -f "${DEPS_PREFIX}/lib/cmake/Catch2/Catch2Config.cmake" ]]; then
    echo "-- building Catch2 3.8.0"
    cmake -S "${SRC}/catch2" -B "${SRC}/catch2/b" -G Ninja \
        -DCMAKE_BUILD_TYPE=Release -DCMAKE_INSTALL_PREFIX="${DEPS_PREFIX}" \
        -DCMAKE_POSITION_INDEPENDENT_CODE=ON \
        -DBUILD_TESTING=OFF > /dev/null
    cmake --build "${SRC}/catch2/b" --target install > /dev/null
fi

# Z3: Ubuntu's libz3-dev ships headers and a shared library but no CMake
# package, which libseqarrange's find_package(Z3 CONFIG) requires. Provide a
# thin config in our own prefix rather than modifying the repository.
Z3_CONFIG_DIR="${DEPS_PREFIX}/lib/cmake/Z3"
Z3_LIB="$(ls /usr/lib/x86_64-linux-gnu/libz3.so* 2>/dev/null | head -1 || true)"
if [[ -n "${Z3_LIB}" && ! -f "${Z3_CONFIG_DIR}/Z3Config.cmake" ]]; then
    echo "-- writing Z3 config shim"
    mkdir -p "${Z3_CONFIG_DIR}"
    cat > "${Z3_CONFIG_DIR}/Z3Config.cmake" <<EOF
# Generated by tests/wsl-verify/linux-deps.sh for the distribution's Z3.
if(NOT TARGET z3::libz3)
    add_library(z3::libz3 SHARED IMPORTED)
    set_target_properties(z3::libz3 PROPERTIES
        IMPORTED_LOCATION "${Z3_LIB}"
        INTERFACE_INCLUDE_DIRECTORIES "/usr/include")
endif()
set(Z3_FOUND TRUE)
EOF
    cat > "${Z3_CONFIG_DIR}/Z3ConfigVersion.cmake" <<'EOF'
set(PACKAGE_VERSION "4.0.0")
set(PACKAGE_VERSION_COMPATIBLE TRUE)
set(PACKAGE_VERSION_EXACT FALSE)
EOF
fi

# The MSlicer bridge is built with --locked --offline by design, so its crate
# cache must be populated once. --locked guarantees the exact pinned versions
# from Cargo.lock; nothing is upgraded here.
MSLICER_MANIFEST="/mnt/c/src/TigerSlicer/src/mslicer/vendor/mslicer/Cargo.toml"
if [[ -f "${MSLICER_MANIFEST}" ]]; then
    if ! cargo fetch --locked --manifest-path "${MSLICER_MANIFEST}" > /dev/null 2>&1; then
        echo "WARNING: cargo fetch failed; the Rust engine will not build offline" >&2
    else
        echo "-- cargo crate cache populated (locked)"
    fi
fi

echo "dependencies ready in ${DEPS_PREFIX}"
